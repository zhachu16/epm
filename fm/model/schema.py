"""Pydantic schema for ``model.json``.

Definitions here are authoritative. Everything derived from them (dependency graphs,
shapes, computed values) is regenerated by the engine.
"""

from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from ..formula.builtins import RESERVED_NAMES

NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

AxisValue = int | str
PeriodValues = dict[AxisValue, float | None]


def check_name(name: str, kind: str) -> str:
    if not NAME_RE.match(name):
        raise ValueError(
            f"{kind} name '{name}' must start with a letter or underscore and contain only "
            "letters, digits and underscores"
        )
    if kind == "metric" and name in RESERVED_NAMES:
        raise ValueError(f"metric name '{name}' is reserved (built-in function or keyword)")
    return name


class _Base(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Settings(_Base):
    name: str = "Untitled model"
    currency: str | None = None
    default_axis: str | None = None


class Axis(_Base):
    kind: Literal["period", "category"] = "period"
    values: list[AxisValue] = Field(min_length=1)
    historical: list[AxisValue] = Field(default_factory=list)
    label: str | None = None

    @model_validator(mode="after")
    def _check_values(self) -> Axis:
        if len(set(map(str, self.values))) != len(self.values):
            raise ValueError("axis values must be unique")
        known = set(map(str, self.values))
        unknown = [v for v in self.historical if str(v) not in known]
        if unknown:
            raise ValueError(f"historical values {unknown} are not axis values")
        return self


class Metric(_Base):
    """A named scalar or series, defined by exactly one of ``value`` or ``formula``.

    ``value`` is a scalar, or a mapping of axis value → number for per-period inputs.
    """

    axis: str | None = None
    unit: str | None = None
    folder: str | None = None
    tags: list[str] = Field(default_factory=list)
    description: str | None = None
    value: float | PeriodValues | None = None
    formula: str | None = None

    @model_validator(mode="after")
    def _one_definition(self) -> Metric:
        defined = [k for k in ("value", "formula") if getattr(self, k) is not None]
        if len(defined) != 1:
            raise ValueError("a metric needs exactly one of 'value' or 'formula'")
        return self


class TableRow(_Base):
    metric: str | None = None
    header: str | None = None
    label: str | None = None
    style: Literal["normal", "subtotal", "total"] | None = None

    @model_validator(mode="after")
    def _one_kind(self) -> TableRow:
        if (self.metric is None) == (self.header is None):
            raise ValueError("a table row needs exactly one of 'metric' or 'header'")
        return self


class Table(_Base):
    """An ordered view of metrics. Tables reference metrics; they never define them."""

    axis: str | None = None
    folder: str | None = None
    description: str | None = None
    rows: list[TableRow] = Field(default_factory=list)


class Check(_Base):
    """A validation rule. Passes when ``expr`` is true, or within ``tolerance`` of zero."""

    expr: str
    tolerance: float = 1e-6
    severity: Literal["error", "warning"] = "error"
    folder: str | None = None
    description: str | None = None


class Model(_Base):
    settings: Settings = Field(default_factory=Settings)
    axes: dict[str, Axis] = Field(default_factory=dict)
    metrics: dict[str, Metric] = Field(default_factory=dict)
    tables: dict[str, Table] = Field(default_factory=dict)
    checks: dict[str, Check] = Field(default_factory=dict)

    @field_validator("axes", "tables", "checks")
    @classmethod
    def _names(cls, v: dict, info) -> dict:
        kind = info.field_name.rstrip("s")
        for name in v:
            check_name(name, kind)
        return v

    @field_validator("metrics")
    @classmethod
    def _metric_names(cls, v: dict) -> dict:
        for name in v:
            check_name(name, "metric")
        return v
